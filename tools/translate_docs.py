"""Translate the English documentation into German and Spanish with Argos Translate.

Argos Translate is free and open-source software (MIT license) that translates
offline with OpenNMT models. The English files are the originals; the German and
Spanish files are generated by this script and should not be edited by hand.

Usage:
    python tools/translate_docs.py

Requires:
    pip install argostranslate

The language models (English to German, English to Spanish) are downloaded on the
first run. Code blocks, inline code, link targets and URLs are copied unchanged.
"""
import pathlib
import re
import sys

import argostranslate.package
import argostranslate.translate

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_LANG = "en"
TARGETS = ["de", "es"]
JOBS = [
    (ROOT / "README.md", {"de": ROOT / "README.de.md", "es": ROOT / "README.es.md"}),
    (ROOT / "docs" / "en" / "MANUAL.md",
     {"de": ROOT / "docs" / "de" / "MANUAL.md", "es": ROOT / "docs" / "es" / "MANUAL.md"}),
]
NOTICE = ("This file was translated automatically from the English original with "
          "Argos Translate. If it differs from the English original, the English original applies.")

# Inline code, markdown links and bare URLs are never translated.
# Program, file and package names are kept as well.
NAMES = ["tute-lote", "pdf-totals", "pdfplumber", "openpyxl", "rapidocr_onnxruntime", "rapidocr", "onnxruntime",
         "opencv-python-headless", "opencv-python", "msvc-runtime", "pdfminer.six", "et_xmlfile",
         "charset-normalizer", "cryptography", "Argos Translate", "PowerShell", "Homebrew", "pip", "uv",
         "Alpine Linux", "Arch Linux", "openSUSE Leap", "openSUSE Tumbleweed", "openSUSE", "Debian",
         "Ubuntu", "Fedora", "FreeBSD", "OpenBSD", "NetBSD", "macOS", "glibc", "musl", "curl", "root",
         "venv", "GitHub", "Microsoft Visual C++", "Rust"]
PROTECT = re.compile(r"`[^`]+`|\[[^\]]*\]\([^)]+\)|https?://\S+"
                     r"|\b[\w-]+(?:\.[\w-]+)*\.(?:py|xlsx|txt|log|md|pdf|zip|exe)\b"
                     r"|(?<![\w-])(?:" + "|".join(re.escape(n) for n in NAMES) + r")(?![\w-])")


# Terminology corrections applied after machine translation. The English word "batch"
# is sometimes left untranslated in German; the correct pharmaceutical term is "Charge".
GLOSSARY = {
    "de": [
        (r"\bBatch-Nummer(n?)\b", r"Chargennummer\1"),
        (r"\bBatchnummer(n?)\b", r"Chargennummer\1"),
        (r"\bein Batch-Label\b", "eine Chargenbezeichnung"),
        (r"\bBatch-Label(s?)\b", "Chargenbezeichnung"),
        (r"\bBatch-Etiketten\b", r"Chargenbezeichnungen"),
        (r"\b(jeden|diesen|einen) Batch\b", lambda m: {"jeden": "jede", "diesen": "diese", "einen": "eine"}[m.group(1)] + " Charge"),
        (r"\b(dem|jedem) Batch\b", lambda m: {"dem": "der", "jedem": "jeder"}[m.group(1)] + " Charge"),
        (r"\b(der|den) Batch\b", "die Charge"),
        (r"\bBatches\b", "Chargen"),
        (r"\bBatch\b", "Charge"),
        (r"\bGrößen\b", "Mengen"),
    ],
    "es": [],
}


def apply_glossary(text, lang):
    for pattern, repl in GLOSSARY.get(lang, []):
        text = re.sub(pattern, repl, text)
    return text


def ensure_models():
    argostranslate.package.update_package_index()
    available = argostranslate.package.get_available_packages()
    installed = {(p.from_code, p.to_code) for p in argostranslate.package.get_installed_packages()}
    for lang in TARGETS:
        if (SOURCE_LANG, lang) in installed:
            continue
        pkg = next(p for p in available if p.from_code == SOURCE_LANG and p.to_code == lang)
        print(f"Downloading model {SOURCE_LANG} -> {lang}")
        argostranslate.package.install_from_path(pkg.download())


def translate_text(text, lang):
    """Translate one paragraph, keeping protected spans unchanged."""
    if not re.search(r"[A-Za-z]{2}", PROTECT.sub("", text)):
        return text
    spans = PROTECT.findall(text)
    masked = text
    for i, span in enumerate(spans):
        masked = masked.replace(span, f"X{i}Q", 1)
    out = argostranslate.translate.translate(masked, SOURCE_LANG, lang)
    if all(out.count(f"X{i}Q") == 1 for i in range(len(spans))):
        for i, span in enumerate(spans):
            out = out.replace(f"X{i}Q", span, 1)
        return out
    # The model changed a placeholder: translate the pieces between the spans separately.
    pieces = PROTECT.split(text)
    result = []
    for i, piece in enumerate(pieces):
        stripped = piece.strip()
        if re.search(r"[A-Za-z]{2}", stripped):
            lead = piece[:len(piece) - len(piece.lstrip())]
            trail = piece[len(piece.rstrip()):]
            piece = lead + argostranslate.translate.translate(stripped, SOURCE_LANG, lang) + trail
        result.append(piece)
        if i < len(spans):
            result.append(spans[i])
    return "".join(result)


def translate_markdown(src, lang):
    out = []
    in_code = False
    for line in src.splitlines():
        if line.startswith("```"):
            in_code = not in_code
            out.append(line)
        elif in_code or not line.strip():
            out.append(line)
        else:
            m = re.match(r"(#+ |- |\d+\. )?(.*)", line)
            prefix, body = m.group(1) or "", m.group(2)
            out.append(prefix + apply_glossary(translate_text(body, lang), lang))
        if len(out) == 1 and out[0].startswith("# "):
            out += ["", translate_text(NOTICE, lang)]
    return "\n".join(out) + "\n"


def main():
    ensure_models()
    for src, targets in JOBS:
        text = src.read_text(encoding="utf-8")
        for lang, dst in targets.items():
            print(f"Translating {src.relative_to(ROOT)} -> {dst.relative_to(ROOT)}")
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(translate_markdown(text, lang), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
